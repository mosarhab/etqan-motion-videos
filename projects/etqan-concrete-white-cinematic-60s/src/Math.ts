export function shot(t: number): View {
  let i = 0;
  while (i < keys.length - 2 && keys[i + 1].t < t) i++;
  const a = keys[i],
    b = keys[i + 1],
    u = smooth((t - a.t) / (b.t - a.t));
  return {
    position: lerp3(a.p, b.p, u),
    target: lerp3(a.q, b.q, u),
    fov: mix(a.f, b.f, u),
  };
}
